//
//	core/Region.h
//
//	平面領域の合成（部品ポリゴンの和集合 ＋ 囲まれた空隙を埋めた領域の外形）。
//	フェーズ非依存の純粋な幾何計算で、SDK も STEP も知らない（CLAUDE.md「core/」）。
//
//	用途: ホームズ君 IFC がロフト（小屋裏収納）の床版を出力しないため、屋根階の
//	床梁（床大梁・床小梁）が作る骨組みからロフト床の外形を合成する（parse/Floor）。
//	梁と梁の隙間（根太間・大梁間）は床なので、和集合そのものではなく**囲まれた
//	空隙を埋めた**領域を床とみなす。
//
//	方式（軸並行セル分割 → 塗り分け → 外形追跡）:
//	  1. 全部品の頂点 X / Y を集めて重複を除き、それらを境界線とするセル格子を作る。
//	     格子線は必ず部品の辺の上に載るので、軸並行の部品なら**近似ではなく厳密**に
//	     セル単位で表現できる（斜めの部品はセル中心のサンプリングで近似する）。
//	  2. 中心が部品ポリゴンの内側にあるセルを「実体」にする。
//	  3. 外周から実体でないセルを塗り広げ（flood fill）、外へ抜けられなかったセル
//	     ＝骨組みに囲まれた空隙を求める。
//	  4. 領域＝「囲まれた空隙」＋「その空隙に接する実体セル」。どの空隙にも接しない
//	     実体——骨組みから外へ突き出しただけの部材や孤立した部材——は落とす
//	     （床梁 1 本分の幅しかないヒゲが床の外形に生えるのを防ぐ）。
//	  5. 領域の連結成分ごとに、外形（面積最大のループ）を反時計回りで返す。
//
//	【近似であること】囲まれた空隙は一律に床として埋めるため、床梁で囲まれた
//	吹抜けがあれば塞がってしまう。骨組みが閉じていない（部材が離れている）場合は
//	空隙が外へ通じてしまい、その部分は床にならない。いずれもホームズ君が床版を
//	出力しないことによる代替手段の限界で、床版があるときは常にそちらを使う。
//

#pragma once

#include "core/Geometry.h"

#include <vector>

namespace HomeskzIfcImport::core
{
	// 部品ポリゴン群（各々は閉じた単純多角形。向きは問わない）が囲む領域——囲まれた
	// 空隙と、それを囲っている部品——の外形を、連結成分ごとに返す。
	//
	// 各外形は反時計回り・共線点を除いた頂点列で、3 点未満に潰れる成分は返さない。
	// 並びはセルの走査順（Y 昇順 → X 昇順）で決まり、入力の順序に依存しない
	// （CLAUDE.md「決定性を守る」）。部品が空・面積が無いときは空を返す。
	std::vector<std::vector<Vec2>> filledUnionOutlines(const std::vector<std::vector<Vec2>>& parts);
} // namespace HomeskzIfcImport::core
