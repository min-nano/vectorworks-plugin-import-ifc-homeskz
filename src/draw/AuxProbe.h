//	**どこに保存されているか**を実機で突き止めるための、読み取り専用のダンプ。
//	図面は一切変更しない（docs/DEV-NOTES.md「実機確認の作法」の「役目を終えた計装は消す」）。
//
//	【なぜ要るか】この設定を書き込む API は SDK にも VectorScript にも無い
//	（docs/DEV-NOTES.md「グラフィック凡例」）。実機のダンプで保存先は
//	**凡例にぶら下がる補助オブジェクト（`ovFirstAuxObject` = 703 の連鎖の先頭にある
//	データオブジェクト `type=76`）**まで絞れたが、**その中身（タグとバイト列）は
//	VectorScript からは読めない**——SDK からしか見えないので、ここで覗く。
//
//	【何を出すか】選択されているグラフィック凡例について
//	  * 補助オブジェクトの連鎖（型・データオブジェクトなら 4 文字タグとバイト数）
//	  * そのタグを**タグ付きデータの容れ物**とみなして総なめした結果
//	    （型 ID × タグ ID の組で要素数が返るものだけ。値も先頭から数個）
//	  * 文書内のビューポートの一覧（名前と内部参照）
//	を 1 つの文字列にする。**別々のビューポートでフィルタした凡例 2 枚**でこれを取れば、
//	差分がそのまま「フィルタ先の持ち方」になる。
//
//	【dev ビルド専用】stable では常に空文字を返す（計装をユーザーの手元で動かさない）。
//
//	【SDK 型を公開しない】戻りは std::string だけなので、draw/DrawUtil.h は要らない
//	（＝SDK を持たない翻訳単位からも include できる。DrawUtil.h 冒頭の約束を破らない）。
//

