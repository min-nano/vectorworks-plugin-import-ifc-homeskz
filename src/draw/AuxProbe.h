//	【一時計装 ── 役目を終えたら消す】グラフィック凡例の**per-instance の設定がどこに
//	保存されているか**を実機で突き止めるための、読み取り専用のダンプ。図面は一切変更しない
//	（docs/DEV-NOTES.md「実機確認の作法」の「役目を終えた計装は消す」）。
//
//	【1 度目（#86）で分かったこと】「ビューポートでフィルタ」は凡例にぶら下がる
//	**データオブジェクトのタグ付きデータ**（容れ物 `'GrLg'` ・型 15 ・タグ 5）にあった。
//	この計装はそれを突き止めるために作られ、役目を終えて #89 で外した。
//
//	【2 度目（今回）に追うもの】残りの per-instance 設定——**ソース定義**（凡例に何を並べるか。
//	既定のままだと空で、スタイル無しの凡例には何も出ない）・集計基準・ソート・イメージの
//	縮率——も同じタグ付きデータに載っている見込みが高い。根拠は SDK ヘッダ:
//	  * `VWFC/Tools/TaggedData.h` の `CTaggedDataContainer` は
//	    `CreateTagString` / `GetTagString` を持つ＝**文字列もタグ付きデータに載る**
//	    （文字列専用の型 ID は無く、byte 配列＝型 1 に載る）
//	  * `VWFC/Tools/DataSerializerSimple.h` の `IDataSerializerTranslate` は
//	    `IsTaggedDataString(type, tagID, version)` を持つ＝**1 つの容れ物の中でタグ ID ごとに
//	    文字列と数値が混在し、版番号のタグを持つ**のが VW の常道
//	1 度目の計装は byte 配列を「先頭 8 個の整数」としてしか出さなかったので、**文字列は
//	素通りしていた**。今回はそこを埋める。
//
//	【何を出すか】**文書内のグラフィック凡例すべて**について
//	  * パラメトリックレコードの全欄（universal 名・OIP の表示名・フィールド種別・値）
//	    ——「イメージの縮率」がどの欄で、いまいくつかが分かる
//	  * 補助オブジェクトの連鎖（型・4 文字タグ・埋め込みの容れ物 ID・16 進ダンプ）
//	  * その容れ物のタグ付きデータの総なめ（**全型 ID × タグ 0〜255**）。byte 配列は
//	    **文字列としても**出し、オブジェクト参照は実体の型と名前まで解く（＝フィルタ先の
//	    ビューポートが**複数**でも全部見える）
//	を 1 つの文字列にする。**手で設定した凡例と素の凡例を同じ文書に置いて 1 回走らせれば、
//	差分がそのまま「その設定の持ち方」になる。**
//
//	【dev ビルド専用】stable では常に空文字を返す（計装をユーザーの手元で動かさない）。
//
//	【SDK 型を公開しない】戻りは std::string だけなので、draw/DrawUtil.h は要らない
//	（＝SDK を持たない翻訳単位からも include できる。DrawUtil.h 冒頭の約束を破らない）。
//

