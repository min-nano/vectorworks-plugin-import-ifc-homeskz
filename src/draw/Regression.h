//
//	draw/Regression.h
//
//	**回帰テスト**（M28。dev ビルドだけ）。**利用者の手元にある過去の物件**を指定した
//	フォルダから集め、1 件ずつ取り込んで、**前回の結果（基準）と引き比べる**。
//
//	【なぜ要るか】このリポジトリは公開されているので、過去の物件の IFC をフィクスチャとして
//	置けない（`tests/fixtures/` に入っているのは公開してよい見本だけ）。一方で退行を一番よく
//	捕まえるのは「実際にやった物件を通し直すこと」で、しかも `draw/` の実描画は CI では
//	検証できずローカルの VectorWorks でしか確かめられない（CLAUDE.md「テスト方針」）。
//	**だから物件はリポジトリの外に置いたまま、実機で回す。**
//
//	【実機フィードバックの往復とは別物】あちらは「**1 つの**物件を、ビルドが変わるたびに
//	取り込み直して PR へ投稿する」もので、縦（時間）に伸びる。こちらは「**多数の**物件を、
//	1 つのビルドで通して基準と引き比べる」もので、横に広がる。PR へは何も投稿しない
//	——結果は手元のダイアログとログに出る。
//
//	【1 回の流れ】
//	  1. 対象フォルダを決める……**そのフォルダの中の IFC を 1 つ選んでもらい、その親を
//	     対象にする**（SDK にフォルダ選択があるかは未確認で、調べるにはリファレンス側の
//	     issue と反映を待つことになる。既存の「開く」ダイアログで足りるなら待つ理由が無い）
//	  2. 走査……シンボリックリンク・ジャンクション・`.lnk`・Finder エイリアスを辿る
//	     （core/FixtureScan.h ＋ draw/Shortcut.h）
//	  3. 取り込み設定を **1 回だけ**尋ね、全件に同じ設定を使う
//	  4. **尋ねることは全部ここまでで尋ね切る**（何件・何分かかる・基準を更新するか）
//	  5. いま開いている図面を作業ファイルへ別名保存し、**1 件ごとにそこへ開き直して**から
//	     取り込む（draw/DocumentFile.h。実機フィードバックの周と同じ作法）
//	  6. 基準と引き比べ、結果ダイアログとログに出す
//
//	【尋ねるのは始まる前だけ】1 件 1 分前後 × 件数なので、40 分を超えることが普通にある。
//	終わったところに確認が待っていると席を離れられない——実機フィードバックの往復で
//	一度そうなって外した作りである（docs/DEV-NOTES.md M23）。だから**基準を更新するかも
//	走らせる前に決める**。
//
//	【図面から消さない】1 件ごとに戻す手立ては**作業ファイルを開き直す 1 本だけ**にして
//	ある。実機フィードバックの往復は 3 段構え（取り消し → 開き直し → 作ったレイヤの削除）
//	だが、あちらは「作業ファイルを用意できなかったとき」の控えが要るからで、こちらは
//	**用意できなければそもそも走らせない**——無人で何十件も回すものを、汚れた図面から
//	始めても読める数字にならない。**利用者のものを消すコードをここには置かない。**
//
//	【SDK 依存】実装は PluginPrefix.h（VectorWorks SDK）を include する。このヘッダは
//	標準ライブラリしか参照しない（CLAUDE.md「依存の向き」）。
//

