//
//	draw/Tag.h
//
//	Phase 2（VW 描画）の断面寸法データタグモジュール（docs/DEV-NOTES.md M13）。ビューポート命
//	令が持つタグ（core::ViewportCommand::tags）を
//	**そのビューポートの注釈**としてデータタグ（PIO "Data Tag"）で置き、対象の横架材へ
//	関連付ける。
//
//	【伏図と軸組図で 1 つの実装】どちらのビューポートも「命令が持つ tags を注釈へ置く」
//	だけで済むのは、**どのタグがどの図に載るかを解析側（parse/Tag）が決めている**ため。
//	断面（軸組図）に載るタグはレイヤでは選べない（切断面に乗るかで決まる）ため、振り分けごと解
//	析側へ寄せてある（parse/Tag.h 冒頭）。
//
//	★**スタイルは作らない・当てない**（スラブ・壁と同じ扱い。draw/DrawUtil.h の
//	「複合オブジェクトの構成」の ★）。タグの中身（断面寸法の書式）も外観も**タグレイアウト**が
//	決めるので、それを**タグ 1 本ずつへ直接**構築し、タグはスタイル無し（unstyled）のままにする。
//	当初は「取り込みのたびにデータタグスタイル（＝シンボル定義）を文書へ作り、全タグへ適用する」
//	形だったが、
//	  * インポートのたびに名前付きリソース（データタグスタイル）が増える。undo では消えないので、
//	    取り消してもリソースだけが残る（DrawUtil.h「取り込み全体の Undo」）。
//	  * 名前が埋まっていれば "-2"、"-3" … と連番になり、同じ中身のスタイルが図面に並ぶ。
//	  * タグの中身はタグレイアウトが全て持っているので、スタイルという間接段を挟む必要が無い。
//	    間接段を挟む分だけ仕組みも要る——シンボル定義のサブタイプにデータタグの内部 ID を
//	    入れ（SetSymbolDefSubType）、パラメータ対応表を「スタイル依存」にする
//	    （SetAllPluginStyleParameters）——そのどれかが漏れると実機で「タグは表示されるのに中身が
//	    空」になった。**適用しない方が段が減って壊れにくい。**
//	という理由で、各タグへ直接与える形へ改めた。個々のタグを後から手動で編集しても他へ波及しない
//	（スタイルで束ねていたときとの唯一の差）。
//
//	【クラスは "寸法"・描画属性は全てクラス属性】タグ本体（データタグ PIO）も、タグレイアウトの
//	中に置く断面寸法の文字も、どちらも**"寸法" クラス**に置き、描画属性（ペン・塗り・線の太さ・
//	不透明度…）はすべて**クラス属性に従わせる**（draw/DrawUtil の SetClassByName ＋
//	SetAllAttributesByClass。他の要素と同じ定型）。こうしておくと寸法の表示を図面側のクラスで
//	一括して変えられる。**中の文字にも要る**——レイアウトの中身は本体のクラスを継承しないので、
//	本体だけに与えると文字が既定クラスのまま残る。
//
//	【タグレイアウト＝タグ 1 本の中身】データタグ PIO の**プロファイルグループ**がタグレイアウトで、
//	そこへ「断面寸法」フィールドを 1 つ置く（リンクされたテキスト＝IDataTagTextLinkSupport で
//	式を持たせたテキスト）。構築方法は次のとおり。
//	  * **生成直後のタグが既にレイアウトを持っていれば、そこへ入れる。** 持っていなければ
//	    **中身を入れてから** SetCustomObjectProfileGroup で渡す——空のグループを先に渡して
//	    後から追加すると、VW が渡した時点でグループを複製している場合に追加したテキストが
//	    参照されないグループへ入る（実機で「オブジェクトは表示されるのにタグレイアウトが空」として
//	    現れた）。渡した後は PIO が実際に持っているものを再取得して中身の数を確認し、複製されて
//	    いればこちらのグループを削除する。
//	  * レイアウトの入り口は**2 つ**あり（GetCustomObjectProfileGroup と、VW2020 で追加された
//	    GetCustomObjectProfileGroupInAux）、どちらに出るかはオブジェクトによって変わるので
//	    両方確認する。
//	  * 中身を構築したら **IDataTagSupport::UpdateUserDefinedTextsUIDs でタグにフィールドを
//	    認識させる**（SDK のコメントに「データタグ**または**データタグスタイルの」とあるとおり、
//	    タグ本体へも使える）。これをしないとタグが式を取得せず、寸法が空のまま表示される。
//
//	【実機から取得した見本】ユーザーが手動で作成した（実際に寸法が表示されている）データタグの構造を
//	診断ダンプで読むと
//	    型86{プロファイル 2件}(型10[式あり])(型0)
//	すなわち **PIO のプロファイルグループにテキスト 1 つ**（式を持つ）だけだった。こちらが
//	生成したものは生成直後のデータタグが持っているロクス（型17＝kLocusNode）が余分に残って
//	いたので、**既定レイアウトのロクスは取り除いて**見本と同じ並びにする。フィールドラベルは
//	テキストの名前では**ない**（見本のテキストには名前が付いていない）。
//
//	【SDK 型を公開するヘッダ】ビューポートのハンドルを引数に取るため、このヘッダは
//	draw/DrawUtil.h・draw/StructuralMember.h と同じく**SDK 型を公開する共通ヘッダ**で、
//	自身で PluginPrefix.h を（DrawUtil.h 経由で）取り込む。したがって**要素ごとの draw/*.h から
//	include してはならない**（DrawUtil.h 冒頭の約束）。呼び出し元は draw/Sheet.cpp と
//	draw/Section.cpp の 2 つだけ。
//
//	【データタグの作法（ローカル確認を重ねて定まった順）】
//	  CreateCustomObject("Data Tag", 挿入点, 角度) → **対象の横架材へ関連付け** →
//	  **タグレイアウトを構築する**（＋フィールドを認識させる）→ 引出線を OFF → ResetObject →
//	  ビューポート注釈へ追加 → タグを更新 → 実位置と実寸を測る →
//	  （全部置いてから）**目標の位置へ動かす**
//	引出線を OFF にするのは、**タグを部材の面ちょうどに置いても既定 ON だと引出線が描画される**
//	ため（位置の決め方は parse/Tag.h）。関連付け先が無い（構造材ツールで描画できずフォールバックの
//	直線になった）横架材のタグは、関連付けだけを省いて置く。
//
//	【ローカル確認で分かった落とし穴（この順序と後処理の理由）】
//	  1. **タグは指定した挿入点に留まらない。** そこで**最後に GetObjectBounds で実位置と
//	     実寸を測って動かす**（タグの実寸はレイアウトの中身が決めるので、部材から離す量も
//	     描画するまで分からない）。ローカル確認で診断行へ実測を出力して確かめた配置のずれ方は
//	     次のとおり。
//	       * 伏図: 実位置は指示した点から**タグ幅の半分だけ −X へ**寄る（実測 3 件が
//	         「指示 (−7788, 4241) → 実測 (−7940, 4241)・幅 305」のように一致）。VW は
//	         挿入点をタグの**右辺中央**として扱っている。
//	       * 軸組図: **配置される場所はビューポートごとにばらばら**で、指示との差に規則が無い。
//	     どちらも測って動かすこの後処理が最終位置を決めるので、VW がどこへ置くかに依らない。
//	     **「VW が関連付け先へ吸着させる」わけではない**——それを前提に「VW が置いた位置
//	     からの相対」で決める実装を試したが、実測はどの基準点候補からも数 m 外れた
//	     （parse/Tag.h「［遠回りの記録］」）。位置は必ず命令の position で決める。
//	  2. **注釈へ後から追加した図形のクラスはビューポートで非表示のまま**。ビューポートの
//	     クラス表示を決める ConfigureViewport はタグを置く前に実行されるので、タグのレイアウトが
//	     その時点で文書に無かったクラスを持ち込むとそのクラスが非表示のまま残る。置いた後に
//	     ShowAllViewportClasses で全クラスを表示へ戻し、ビューポートを再更新する。
//	  3. **断面（軸組図）の注釈空間は横方向の原点がモデルと違う**（高さは合うのに横だけ
//	     一定量ずれた）。補正は解析側が持つ（parse/Tag が core::sectionAlongOrigin で済ませる）。
//	     **ローカル確認で正しい位置に表示されることを確認済み。**
//
//	実描画（タグの表示・レイアウトの反映・注釈空間での位置）はローカルの VectorWorks で
//	目視確認する（docs/DEV-NOTES.md M13）。
//

#pragma once

#include "draw/DrawUtil.h"

#include "core/Document.h"

#include <cstddef>
#include <string>

namespace HomeskzIfcImport::draw
{
	// タグ描画の集計。**実描画はローカルの VW でしか確認できない**ので、タグが 1 つも
	// 表示されない・中身が空で表示されるときに原因（タグレイアウトを構築できない／関連付け先が
	// 無い）を切り分けられるように件数で記録する（draw/Member の診断と同じ方式）。

	struct TagCounts
	{
		std::size_t drawn = 0;	// 注釈に置けたタグ
		std::size_t failed = 0; // PIO を生成できなかった／注釈に入れられなかった
		std::size_t unassociated = 0; // 関連付け先の横架材ハンドルが無かった
		std::size_t layoutFailed = 0; // タグレイアウトを構築できなかった（断面寸法が空になる）
		std::size_t leaderLeft = 0; // 引出線を OFF にできなかった（引出線が残る）
		std::size_t classesShown = 0; // タグを置いた後に表示へ戻せたクラス数（0 なら表示されない）
		std::size_t updateFailed = 0; // クラスを戻した後の再更新に失敗したビューポート
		std::size_t unmeasured = 0; // 実位置を測れず動かせなかったタグ
		// 高さの注記を部材の高さに連動させられず、取り込んだ時点の文字で置いたタグ（横架材の
		// レイヤが階に属していなかった。draw/Tag.cpp の LinksHeight）
		std::size_t heightUnlinked = 0;
		bool textStyleMissing = false; // 文字スタイル（"寸法(6pt)"）が文書に無かった
		bool linkMissing = false; // テキストをタグフィールドにできなかった（式が入らない）
		// 置いたタグ 1 本の実際の状態（レイアウトの中身の数）。**実描画はローカルの VW でしか
		// 確認できない**ので、「タグはあるのに中身が空」のときにレイアウトが空なのかどうかを
		// 実機から記録するための情報。正常なら空文字（診断に出力しない）。
		std::string firstTag;
	};

	// データタグ PIO の定義を**設定ダイアログを表示せずに**用意する。タグを 1 つでも置く
	// フェーズ（伏図・軸組図）の先頭で 1 回呼ぶ（理由は DrawUtil の
	// PrepareCustomObjectDefinition）。
	void prepareDataTagPlugin();

	// ビューポート 1 枚分のタグを注釈として置く。置けた数を返し、内訳を counts へ加算する
	// （複数のビューポート分を 1 つの counts へ加算してよい）。memberHandles は drawMembers が
	// 記録した「命令インデックス → 横架材ハンドル」の対応表。タグの中身（タグレイアウト）は
	// **1 本ずつこの中で構築する**（上記 ★「スタイルは作らない・当てない」）。
	std::size_t drawViewportTags(MCObjectHandle viewport, const core::ViewportCommand& command,
								 const ObjectHandleTable& memberHandles, TagCounts& counts);

	// 集計を人が読める 1 行の診断にする（異常が無ければ空文字）。label は図の種別
	// （"伏図" / "軸組図"）。
	std::string tagDiagnostics(const std::string& label, const TagCounts& counts);
} // namespace HomeskzIfcImport::draw
