//
//	draw/Feedback.h
//
//	**実機フィードバックの往復**（docs/DEV-NOTES.md M23〜M25）。開発版（dev）ビルドで
//	取り込みを走らせた結果を、そのビルドの元になった PR へ投稿する——この 1 周ぶんを
//	受け持つ。
//
//	【本番のコマンドは往復を知らない（M25）】M24 までは、この往復が**本番の取り込み
//	コマンドの中**に織り込まれていた——記憶を読んでファイル選択を飛ばす分岐、「次は更新を
//	尋ねずに入れてよいか」を意味する戻り値、投稿できたら結果ダイアログを出さない分岐。
//	`#ifdef VW_DEV_BUILD` の外にあるので**安定版にも同じ制御フローが入っており**、本番の
//	経路にバグを混ぜる余地になっていた。
//
//	M25 で往復を**dev だけの実機テストのコマンド**（`runTestRound`。入口は
//	src/Extensions/ExtTestMenu）へ丸ごと移し、本番の取り込みコマンドからは往復の分岐を
//	1 つ残らず取り除いた。両者が共有するのは**絵を作るところだけ**（draw/ImportRun.h の
//	`runImportRound`）で、テストで走るのは本番と同じコードである。
//
//	【1 周の形】
//	  1. **取り込みの前に**、送るかどうか・宛先・伏せ字を決める。続きの周は記憶から即座に
//	     決まるので**何も出ない**。
//	  2. 準備（`prepareDrawingForRound`）→ 取り込み（draw/ImportRun）
//	  3. 終わったら**黙って投稿する**。結果ダイアログも出さない。
//	  4. 直った版が push され、CI が dev プレリリースを出したら、殻のパレットが**尋ねずに**
//	     その版を入れ、本体を読み直して 1 へ戻る（src/FeedbackLoop.h）。パレットを閉じて
//	     いれば、人がテストのコマンドを 1 回実行すれば同じところから続く。
//
//	【続きの周は「新しいビルドが来たとき」だけ】記憶に残した sha と動いているビルドが同じ
//	なら、それは往復の続きではない——同じビルドで取り込み直しても同じ数字が並ぶだけなので、
//	**取り込まない**（往復を回し直すだけにする）。M24 まではここで「新しい 1 周目」として
//	取り込み直していたが、パレットが開いている最中にメニューを押した人が round 1 を二重に
//	投稿する原因になった（実機で発生。docs/DEV-NOTES.md M25）。
//
//	【自動の周（M24）】投稿できた周の終わりに記憶の `loop` を立て、殻のモードレスなパレット
//	がそれを見て、新しいビルドが出るたびに入れて取り込み直す（src/FeedbackLoop.h）。本体が
//	そのために持つ口は 2 つだけ——記憶を見せる（feedbackLoopStatus）と「止めた」を受ける
//	（endFeedbackLoop）。止める入口はパレットと Claude の合図（PR コメントの `control=stop`）
//	で、どちらも記憶は消さない。
//
//	【前の周の図はプラグインが取り除く（M25）】2 周目以降は同じ文書へもう一度描くので、
//	前の周が残っていると図が二重になる。**プログラムから「取り消し」を掛ける道は 2 つとも
//	閉じている**——ISDK の undo 実行 API は閉じたイベントに効かず（SDK リファレンス #23）、
//	メニューコマンドを名前で起動する API も存在しない（同 #27。どちらもヘッダ根拠つきで
//	確定）。残る唯一の道が**レイヤのハンドルを直接消す**ことで、これは実機で確認されている
//	（同 #25。Findings「Undo」）。取り込みの前に `prepareDrawingForRound` が、**前の周が
//	自分で作ったレイヤだけ**を名指しで取り除く。作法（自分で undo イベントを開いて閉じる・
//	シートを先に消す）と安全弁は `draw/DrawUtil` の `RemoveCreatedLayers` が持つ。
//
//	おかげで**利用者に頼むことはコマンドを 1 回押すことだけ**になった。実際にどうだったかは
//	描画側の実測として PR コメントへ載せる（parse/Feedback.cpp）ので、読む側はそれを見る。
//
//	【取り込みのあとに人の操作を残さない】**決めることは全部、取り込みが始まる前に決める。**
//	取り込みは 1 分以上かかるので、終わったところに確認が待っていると、その人は席を離れ
//	られない——それでは「実行して放っておく」が成立しない（実機の指摘）。だから宛先も
//	伏せ字もトークンの登録も前に済ませ、終わったあとは投稿して黙る。
//
//	【所見は PR へ載せない】絵を見て気付いたことは**人が Claude とのチャットへ直接書く**。
//	所見を書くには結局その人が実機を見ている必要があり、見ているならチャットのほうが速く、
//	スクリーンショットも貼れる。プラグインが所見を訊く仕組みは持たない（M23 で一度作って
//	外した。docs/DEV-NOTES.md「所見はプラグインの仕事ではなかった」）。
//
//	【なぜ要るか】`draw/` の実描画は CI では検証できず、ローカルの VectorWorks でしか
//	確かめられない（CLAUDE.md「テスト方針」）。そのため 1 往復ごとに
//	「新しいビルドを入れる → 図面を戻す → ファイルを選ぶ → 設定を選ぶ → 取り込む →
//	ログを写して貼る」という手作業が挟まり、これが**実装そのものより時間を食っていた**。
//
//	【入れるのも殻】新しい本体を効かせるには載っている本体を降ろす必要があり、それが
//	できるのは**本体のコードがスタックに 1 つも無いとき**だけである（src/PayloadSession.h）。
//	だから入れ替えは必ず殻の側で起きる——おかげで**インストールの経路はこのリポジトリに
//	1 本しかない**（src/UpdaterFlow.cpp）。往復のために 2 本目を作らない。
//
//	【殻の道具を借りる】同梱スクリプトの実行は本体からは手が届かないので、境界越しに
//	借りたもの（draw/HostServices）を使う。借りられなければこのコマンドが静かに無効になる
//	（本番の取り込みは何も変わらない）。
//
//	【SDK 依存】実装は PluginPrefix.h（VectorWorks SDK）と VWFC のダイアログを include する。
//	このヘッダは core/ までしか参照しない。
//

#pragma once

#include <string>

namespace HomeskzIfcImport::draw
{
	// フィードバックの往復が**そもそも使えるか**（dev ビルドで、殻がスクリプトを
	// 貸してくれているか）。使えないときは取り込みが従来どおり動くだけである。
	bool feedbackAvailable();

	// **実機テストの 1 周**（M25）。**このコマンドだけが往復を知っている。**
	//
	//   1. 続きの周（記憶があり、動いているビルドがそれと違う）なら**何も尋ねずに**
	//      前の周と同じ条件で取り込み、投稿する。
	//   2. 記憶が無ければ 1 周目として、IFC・取り込み設定・宛先の PR・伏せ字を尋ねてから
	//      取り込み、投稿する。**尋ねるのは取り込みが始まる前だけ**（下記）。
	//   3. 記憶があって**同じビルドが動いている**なら、取り込まない——同じ数字が並ぶだけ
	//      なので 1 分をかける意味が無い。往復を回す（止まっていたら回し直す）だけにする。
	//
	// allowDialogs … メニューから実行したとき true。パレットの周（src/FeedbackLoop.h）は
	//                false で、そのときダイアログは 1 枚も出ない——3 の入口も通らない
	//                （パレットがここへ来るのは新しいビルドを入れた直後だけ）。
	// active       … 戻ったとき往復が回っている状態か。殻はこれを見てパレットを開く
	//                （src/Extensions/ExtTestMenu.cpp）。
	//
	// 戻り値は「この呼び出しが成立したか」。人がやめた・投稿できなかったときは false で、
	// 理由は結果ダイアログかアラートで既に伝えてある。
	bool runTestRound(bool allowDialogs, bool& active);

	// -----------------------------------------------------------------------
	// **モードレスの往復（M24）が殻から尋ねてくるもの**（src/PayloadAbi.h の
	// vw_payload_loop_status / vw_payload_loop_end。駆動は src/FeedbackLoop.h）。
	//
	// 往復の記憶を key=value の行で返す（active / repo / pr / branch / round / build /
	// posted）。active は「send かつ round>0 かつ loop」——投稿できた周の終わりに立ち、
	// 止めたときに下りる（core::FeedbackSession::loop）。記憶が無い・使えないビルドなら
	// active=0 だけを返す。
	std::string feedbackLoopStatus();

	// 自動の往復を止めた。記憶の loop を下ろす（**記憶は消さない**——人がメニューから
	// 実行すれば続きの周として走る）。notifyPr なら PR へ「終えました」を 1 通投稿する
	// （目印は `control=ended`。読む側が待ち続けないため）。
	void endFeedbackLoop(const std::string& reason, bool notifyPr);
} // namespace HomeskzIfcImport::draw
