//
//	draw/Legend.h
//
//	Phase 2（VW 描画）のグラフィック凡例モジュール（docs/DEV-NOTES.md M13）。シート命令が持つ
//	凡例（core::SheetCommand::legend）を
//	**そのシートレイヤの上**に VW 標準の "GraphicLegend" PIO で置く。
//
//	【そのシートのビューポートでフィルタする】凡例に並ぶのは**そのシートのビューポートに
//	映っているシンボルだけ**にする（＝OIP の「ビューポートでフィルタ…」を取り込み時に
//	済ませる）。これを設定する API は SDK にも VectorScript にも無く、**凡例にぶら下がる
//	データオブジェクトのタグ付きデータ**に保存されている——実機のバイト列で突き止めた
//	（経緯と読み方は docs/DEV-NOTES.md「グラフィック凡例」）。書き込みに要るのは 4 つ:
//	  * 容れ物 `'GrLg'`（0x47724C67。**データオブジェクトのタグ `'DMDT'` ではない**——
//	    あれは入れ物の入れ物で、本当の容れ物 ID は中身の +86 に入っている）
//	  * 型 15（`kTaggedDataObjectRefArrayTypeID` ＝ オブジェクト参照の配列）
//	  * タグ 5
//	  * 値＝フィルタ先ビューポートの `GetObjectInternalIndex`
//	`ISDK::TaggedDataCreate` ＋ `TaggedDataSet` で書き、**`ResetObject` より前**に済ませる
//	（凡例の作り直しでセルが決まるため）。
//
//	【ビューポート注釈ではない】データタグ（draw/Tag）はビューポートの注釈空間に入るが、
//	凡例は**シートレイヤに直接置く**（＝用紙の上に載る）。したがって位置は用紙座標で、
//	ビューポートの中身とは無関係に決まる。**置き場所は命令ではなく用紙の割り付けが決める**
//	（M18。core::planLayout が凡例のために空けた右の 1 列の右上へ寄せる）。
//
//	【大きさは実測して割り付けへ返す】凡例の幅は**その図面に何が並ぶか**で決まるので、
//	「これだけ空けておけば足りる」という定数を置かない（core/Layout.h「凡例の幅は定数で
//	持たない」）。置いて・流し込んで・measureLegendWidth で測った幅を伏図の縮尺の計算へ
//	渡し、最後に placeLegends で右上へ揃える。
//
//	【★スタイルは作らないし当てない】凡例は**スタイル無しのオブジェクト**として置く
//	（スラブ・壁・データタグと同じ扱い。docs/DEV-NOTES.md「グラフィック凡例」）。
//	  * ユーザーの図面に名前付きリソースを増やさない（CLAUDE.md 開発の基本方針 4）。
//	  * かつては "基礎伏図凡例" / "床伏図凡例" というグラフィック凡例スタイルを当てて中身を
//	    決めていた。**スタイルが無い文書では凡例が空の箱になり**、名前が 1 文字違うだけで
//	    同じことが起きる——取り込みの結果が図面の外の資源に左右されるのをやめた。
//	  * したがって `SetPluginObjectStyle` も、スタイルの中身を流し込む `UpdateStyledObjects`
//	    も呼ばない（スタイルが無いのだから、置いた時点の `ResetObject` で中身が決まる）。
//
//	【ソース定義（何を並べるか）も書き込む ── 実験】凡例に何が並ぶかを決めるソース定義は
//	**PIO のパラメータでは設定できない**（ソース定義はボタンのフィールドで、選んだソースを
//	保持する欄がパラメトリックレコードに無いことを実オブジェクトのフィールドダンプで確認済み。
//	ISDK にも凡例のソースを触る呼び出しは無い＝sdk-grep で確認）。そして**既定のソースは空**
//	なので、スタイルを当てないと凡例は 1 セットも表示しない（実機で確認）。
//	そこでフィルタと同じ手口——**タグ付きデータ**——でソース定義も書き込む:
//	  * 容れ物 `'GrLe'`（0x47724C65。フィルタの `'GrLg'` と 1 文字違い）
//	  * 型 1（`kTaggedDataByteArrayTypeID`）・タグ 0・22 バイト
//	  * 値＝**手で「凡例ソースの定義...」を設定した凡例から写したバイト列**
//	検索条件は文字列ではなく **11 個の 16 ビット値のトークン列**で、実機の 4 枚を突き合わせると
//	**6 番目だけが条件で変わった**（`T=SYMBOL` の 3 枚が 15、`T=PLUGINOBJECT` の 1 枚が 86）。
//	つまり残りは `( INVIEWPORT & ( T = … ) )` の器で、**6 番目にオブジェクトの型番号を入れれば
//	条件を差し替えられる**。いま入れているのは **15＝シンボル**——凡例を載せているのは基礎伏図
//	だけで、並べたいのはアンカーボルト（ハイブリッドシンボル）だから。構造材ツールの部材
//	（横架材・柱・垂木）を並べたくなったら 86 にする。
//	**写した値が文書や VW の版をまたいで通用するかは確かめられていない**ので、これは実験で
//	ある。実機で「並ぶかどうか」を見て、駄目ならスタイルを当てる方式へ戻す
//	（docs/DEV-NOTES.md「グラフィック凡例」）。
//
//	【SDK 型を公開するヘッダ】シートレイヤのハンドルを引数に取るため、draw/Tag.h・
//	draw/DrawUtil.h と同じく**SDK 型を公開する共通ヘッダ**で、自分で PluginPrefix.h を
//	（DrawUtil.h 経由で）取り込む。したがって**要素ごとの draw/*.h から include しては
//	ならない**（あちらは SDK を持たない翻訳単位＝Extensions/ExtMenu からも include される
//	ため。DrawUtil.h 冒頭の約束）。呼び出し元は draw/Sheet.cpp だけ。
//
//	【凡例の作法】シートレイヤをアクティブに → CreateCustomObject("GraphicLegend", 位置, 0)
//	→ 箱幅 BoxWidth を与える → ソース定義とビューポートでフィルタ（上記のタグ付きデータ）
//	→ ResetObject → 線の太さ・塗りをオブジェクトの属性として設定
//	  * **箱幅を与えるのは、点で生成すると幅 0 になる**ため（凡例は矩形モードの PIO で、
//	    対話作成ではユーザーが描いた矩形の幅にレイアウトが追従する）。幅 0 のままだと
//	    サイズ 0 でリサイズハンドルも掴めない。
//	  * **イメージの縮率はその伏図の縮尺に合わせる**（1:100 の伏図なら 1:100）。凡例に並ぶ
//	    のは図に出ているのと同じ部材なので、縮率が図と違うと凡例のシンボルだけが大小する。
//	    書き先はパラメトリックレコードの `ImageScale`（分母を実数で持つ。1:50 なら 50）——
//	    **表示名が空で OIP の項目名からは引けない**ので universal 名で直に書く（実機の
//	    ダンプで確定）。**縮尺は用紙への収まりが決める**（core::planLayout）ので、置くときで
//	    はなく**縮尺が決まってから** applyLegendImageScale でまとめて与える。
//	  * **見た目はクラスでは制御できない**——凡例 PIO が内部で描く枠線・セルは、本体のクラスに
//	    もカレントクラスにも従わず一般クラスの属性で作図される。そこでクラスによる制御は諦め、
//	    線の太さ（0.13mm）と塗り（なし）を**オブジェクトの属性として直接**設定する。
//
//	実描画（凡例の中身・大きさ・位置）はローカルの VectorWorks で目視確認する
//	（docs/DEV-NOTES.md M13「ローカル確認」）。
//

#pragma once

#include "draw/DrawUtil.h"

#include "core/Document.h"

#include <cstddef>
#include <string>

namespace HomeskzIfcImport::draw
{
	// 凡例描画の集計。**実描画はローカルの VW でしか確認できない**ので、凡例が出ない・
	// 大きさがおかしいときに原因（PIO を作れない／箱幅を書けない／縮率を書けない）を
	// 切り分けられるように件数で持ち帰る（draw/Tag の TagCounts と同じ流儀）。
	struct LegendCounts
	{
		std::size_t drawn = 0;	   // シートレイヤに置けた凡例
		std::size_t failed = 0;	   // PIO を作れなかった
		std::size_t widthLeft = 0; // 箱幅を書けなかった（幅 0 のまま潰れる）
		std::size_t paramsFailed = 0; // PIO として開けず、パラメータを 1 つも書けなかった
		std::size_t sourced = 0;	// ソース定義を書けた
		std::size_t sourceLeft = 0; // ソース定義を書けなかった（何も並ばない）
		std::size_t filtered = 0;	// そのシートのビューポートでフィルタできた
		std::size_t filterLeft = 0; // フィルタを書けなかった（文書中の全シンボルが並ぶ）
		std::size_t scaleLeft = 0; // 縮率が読み戻しで一致しなかった（図と揃わない）

		// 縮率に**書いた値**と**読み戻した値**。一致しないときだけ診断へ出す
		// （下の verifyLegendImageScale）。
		double scaleAsked = 0.0;
		double scaleGot = 0.0;

		// 置いた凡例そのもの。**中身が流し込まれた後に大きさが決まる**ので、幅の実測と
		// 位置合わせ、そしてイメージの縮率は**置き終えてから**まとめて行う（下記）。
		std::vector<MCObjectHandle> objects;
	};

	// グラフィック凡例 PIO の定義を**設定ダイアログを出さない**で用意する。凡例を 1 つでも
	// 置くフェーズ（伏図）の先頭で 1 回呼ぶ。理由は draw/Tag の prepareDataTagPlugin と同じ
	// （CreateCustomObject が最初の 1 個で定義を作るとき、既定ではダイアログが出て
	// インポートが止まる）。**静的フラグで 1 回だけにはしない**——定義は文書ごとなので、
	// 次の文書へのインポートで抜けてしまう。
	void prepareGraphicLegendPlugin();

	// 凡例 1 つをシートレイヤの上に置く。置けたら true を返し、内訳を counts へ積む
	// （複数のシートぶんを 1 つの counts へ積んでよい）。**カレントレイヤをそのシートレイヤへ
	// 移す**（PIO はカレントレイヤに入るため）ので、呼び出し側は必要なら後で戻すこと。
	//
	// **命令（core::LegendCommand）は受け取らない。** 中身も置き場所も縮率も命令には無く
	// （core/Document.h の LegendCommand）、凡例が「有る」ことだけが意味を持つので、
	// 呼び出し側が `has_value()` で判断すれば足りる。
	//
	// where は**生成位置**（用紙 mm）。仮の点でよい——**最終的な位置合わせは placeLegends
	// が行う**（凡例の大きさは並ぶ中身が決まって初めて定まるため。下記）。
	//
	// filterViewport には**そのシートに載せたビューポート**を渡す（nil なら絞り込まない）。
	// 凡例はそのビューポートに映っているシンボルだけを並べる（ヘッダ冒頭「そのシートの
	// ビューポートでフィルタする」）。
	bool drawSheetLegend(MCObjectHandle sheetLayer, const core::Vec2& where,
						 MCObjectHandle filterViewport, LegendCounts& counts);

	// 置いた凡例を作り直して中身を流し込む。**すべての凡例を置き終えてから**呼ぶ。
	//
	// **2 度呼んでよい**（作り直しは何度行っても同じ結果になる）。伏図では
	// 「凡例を置く → 作り直す → 幅を測って縮尺を決める → ビューポートを仕上げる →
	// もう一度作り直す」という順で使う——凡例に並ぶのはビューポートに映るシンボルなので、
	// 図が仕上がった後にもう一度作り直して取りこぼしを無くす（draw/Sheet）。
	//
	// **スタイルは使わない**（ヘッダ冒頭の ★）ので、中身を決めるのは各オブジェクトに
	// 書き込んだソース定義とビューポートのフィルタ。したがって「流し込む」＝`ResetObject`。
	void refreshLegends(const LegendCounts& counts);

	// 置いた凡例のイメージの縮率を scale（1:100 なら 100）に合わせる。**伏図の縮尺が
	// 決まってから**呼ぶ——縮尺は用紙への収まりで決まり、凡例の幅を測った後に決め直される
	// ことがある（core::planLayout。draw/Sheet の順序）。0 以下なら何もしない。
	void applyLegendImageScale(LegendCounts& counts, double scale);

	// 縮率を**読み戻して**確かめる（最後の作り直しの後に呼ぶ）。一致しなければ件数と
	// 「書いた値／読めた値」を counts へ残し、診断に出す。
	//
	// **なぜ確かめるか。** 実機で「伏図が 1:50 でも 1:75 でも凡例は 1:50」になった。
	// 原因は 2 つのどちらか——(1) 書き込みが通っていない（作り直しで戻される等）、
	// (2) `ImageScale` が OIP の「イメージの縮率」ではない（下の灰色の「カスタム 1:」に
	// 当たり、実際の縮率はイメージの定義側が持つ）。読み戻した値が分かれば 1 回で切り分く。
	void verifyLegendImageScale(LegendCounts& counts);

	// 置いた凡例のうち**いちばん広いものの幅**（用紙 mm）。凡例が 1 つも無い・どれも
	// 測れないときは 0。
	//
	// **必ず refreshLegends の後に呼ぶ**——中身が流し込まれるまで凡例の大きさは
	// 決まらない。この実測が伏図の縮尺を決める（core::planLayout の legendWidth）。
	// 凡例の幅を定数で決め打ちにしない理由は core/Layout.h「凡例の幅は定数で持たない」。
	double measureLegendWidth(const LegendCounts& counts);

	// 置いた凡例の**右上を topRight へ揃える**（用紙 mm。core::planLayout の
	// legendTopRight）。中身が流し込まれて大きさが定まった後に呼ぶこと。測れないものは
	// その場に残す（凡例は出る。位置だけずれる）。
	void placeLegends(const LegendCounts& counts, const core::Vec2& topRight);

	// 集計を人が読める 1 行の診断にする（異常が無ければ空文字）。
	std::string legendDiagnostics(const LegendCounts& counts);
} // namespace HomeskzIfcImport::draw
