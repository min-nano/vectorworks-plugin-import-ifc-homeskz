//
//	draw/Legend.h
//
//	Phase 2（VW 描画）のグラフィック凡例モジュール（docs/DEV-NOTES.md M13）。シート命令が持つ
//	凡例（core::SheetCommand::legend）を
//	**そのシートレイヤの上**に VW 標準の "GraphicLegend" PIO で置く。
//
//	【ビューポート注釈ではない】データタグ（draw/Tag）はビューポートの注釈空間に入るが、
//	凡例は**シートレイヤに直接置く**（＝用紙の上に載る）。したがって位置は用紙座標で、
//	ビューポートの中身とは無関係に決まる。
//
//	【★スタイルは作らないし当てない】凡例は**スタイル無しのオブジェクト**として置く
//	（スラブ・壁・データタグと同じ扱い。docs/DEV-NOTES.md「グラフィック凡例」）。
//	  * ユーザーの図面に名前付きリソースを増やさない（CLAUDE.md 開発の基本方針 4）。
//	  * かつては "基礎伏図凡例" / "床伏図凡例" というグラフィック凡例スタイルを当てて中身を
//	    決めていた。**スタイルが無い文書では凡例が空の箱になり**、名前が 1 文字違うだけで
//	    同じことが起きる——取り込みの結果が図面の外の資源に左右されるのをやめた。
//	  * したがって `SetPluginObjectStyle` も、スタイルの中身を流し込む `UpdateStyledObjects`
//	    も呼ばない（スタイルが無いのだから、置いた時点の `ResetObject` で中身が決まる）。
//
//	【中身（並ぶセル）は凡例オブジェクト自身が決める】凡例に何が並ぶか——ソース定義
//	（どのビューポートのオブジェクトを集めるか）・集計基準・行レイアウト・行ラベル——は
//	**PIO のパラメータでは設定できない**（ソース定義はボタンのフィールドで、選んだソースを
//	保持する文字列フィールドがパラメトリックレコードに無いことを実オブジェクトのフィールド
//	ダンプで確認済み。ISDK にも凡例のソースを触る呼び出しは無い＝sdk-grep で確認）。
//	スタイル無しで置いた凡例は**その PIO の既定のソース**で中身を集めるので、**何が並ぶかは
//	ローカルの VectorWorks で確認する**（詰めるならユーザーが凡例の「凡例ソースの定義...」で
//	直す。図面の中で完結し、名前付きリソースは増えない）。
//
//	【SDK 型を公開するヘッダ】シートレイヤのハンドルを引数に取るため、draw/Tag.h・
//	draw/DrawUtil.h と同じく**SDK 型を公開する共通ヘッダ**で、自分で PluginPrefix.h を
//	（DrawUtil.h 経由で）取り込む。したがって**要素ごとの draw/*.h から include しては
//	ならない**（あちらは SDK を持たない翻訳単位＝Extensions/ExtMenu からも include される
//	ため。DrawUtil.h 冒頭の約束）。呼び出し元は draw/Sheet.cpp だけ。
//
//	【凡例の作法】シートレイヤをアクティブに → CreateCustomObject("GraphicLegend", 位置, 0)
//	→ 箱幅 BoxWidth を与える → イメージの縮率を伏図ビューポートの縮尺に合わせる →
//	ResetObject → 線の太さ・塗りをオブジェクトの属性として設定
//	  * **箱幅を与えるのは、点で生成すると幅 0 になる**ため（凡例は矩形モードの PIO で、
//	    対話作成ではユーザーが描いた矩形の幅にレイアウトが追従する）。幅 0 のままだと
//	    サイズ 0 でリサイズハンドルも掴めない。
//	  * **イメージの縮率はその伏図ビューポートの縮尺に合わせる**（1:50 の伏図なら 1:50）。
//	    凡例に並ぶのは図に出ているのと同じ部材なので、縮率が図と違うと凡例のシンボルだけが
//	    大小する。縮尺は**ビューポートを仕上げたときに読んだ値**（draw/DrawUtil の
//	    `ViewportFinish::scale`）をそのまま渡す——同じ縮尺を 2 か所で読み直さない。
//	    パラメータ名は環境（PIO の登録）でしか分からないので候補と OIP の表示名から引き、
//	    **フィールドの種別（EFieldStyle）で入れ方を変える**（ポップアップ・文字なら "1:50"
//	    という表記、実数なら分母 50）。書いたら読み戻して確かめる。
//	  * **見た目はクラスでは制御できない**——凡例 PIO が内部で描く枠線・セルは、本体のクラスに
//	    もカレントクラスにも従わず一般クラスの属性で作図される。そこでクラスによる制御は諦め、
//	    線の太さ（0.13mm）と塗り（なし）を**オブジェクトの属性として直接**設定する。
//
//	実描画（凡例の中身・大きさ・位置）はローカルの VectorWorks で目視確認する
//	（docs/DEV-NOTES.md M13「ローカル確認」）。
//

#pragma once

#include "draw/DrawUtil.h"

#include "core/Document.h"

#include <cstddef>
#include <string>

namespace HomeskzIfcImport::draw
{
	// 凡例描画の集計。**実描画はローカルの VW でしか確認できない**ので、凡例が出ない・
	// 大きさがおかしいときに原因（PIO を作れない／箱幅を書けない／縮率を書けない）を
	// 切り分けられるように件数で持ち帰る（draw/Tag の TagCounts と同じ流儀）。
	struct LegendCounts
	{
		std::size_t drawn = 0;	   // シートレイヤに置けた凡例
		std::size_t failed = 0;	   // PIO を作れなかった
		std::size_t widthLeft = 0; // 箱幅を書けなかった（幅 0 のまま潰れる）
		std::size_t scaleLeft = 0; // イメージの縮率を書けなかった（凡例だけ縮尺が揃わない）
		std::size_t scaleUnknown = 0; // 伏図ビューポートの縮尺が分からなかった（合わせ先が無い）
		std::size_t paramsFailed = 0; // PIO として開けず、パラメータを 1 つも書けなかった

		// 縮率を書けなかったときに控える、その凡例のパラメータ名の一覧（universal 名と
		// OIP の表示名）。**イメージの縮率のパラメータ名は SDK ヘッダにもマニュアルにも無く、
		// 実機の PIO にしか無い**ので、候補名がどれも外れたときに正しい名前を実機から持ち帰る
		// ための目（draw/Tag の firstTag と同じ流儀）。正常なら空文字（診断に出さない）。
		std::string scaleParams;
	};

	// グラフィック凡例 PIO の定義を**設定ダイアログを出さない**で用意する。凡例を 1 つでも
	// 置くフェーズ（伏図）の先頭で 1 回呼ぶ。理由は draw/Tag の prepareDataTagPlugin と同じ
	// （CreateCustomObject が最初の 1 個で定義を作るとき、既定ではダイアログが出て
	// インポートが止まる）。**静的フラグで 1 回だけにはしない**——定義は文書ごとなので、
	// 次の文書へのインポートで抜けてしまう。
	void prepareGraphicLegendPlugin();

	// 凡例 1 つをシートレイヤの上に置く。置けたら true を返し、内訳を counts へ積む
	// （複数のシートぶんを 1 つの counts へ積んでよい）。**カレントレイヤをそのシートレイヤへ
	// 移す**（PIO はカレントレイヤに入るため）ので、呼び出し側は必要なら後で戻すこと。
	//
	// viewportScale はその伏図ビューポートの縮尺（1:50 なら 50。draw/DrawUtil の
	// `ViewportFinish::scale`）で、凡例のイメージの縮率をこれに合わせる。**0 は「縮尺が
	// 分からなかった」**という意味で、そのときは縮率を触らない（PIO の既定のまま）。
	bool drawSheetLegend(MCObjectHandle sheetLayer, const core::LegendCommand& command,
						 double viewportScale, LegendCounts& counts);

	// 集計を人が読める 1 行の診断にする（異常が無ければ空文字）。
	std::string legendDiagnostics(const LegendCounts& counts);
} // namespace HomeskzIfcImport::draw
