//
//	draw/SettingsDialog.h
//
//	取り込み設定ダイアログ（docs/DEV-NOTES.md M20 / M28）。**IFC を選んだ直後**に 1 枚表示し、
//	「どの要素を図面のどのシンボルで置くか」と「各シートレイヤへ置く**図面枠のスタイル**」
//	（core::ImportOptions）を利用者に決めてもらう。
//
//	【なぜ描画側にあるか】選択肢は「現在開いている図面にあるシンボル定義」で、それを
//	知っているのは VectorWorks だけ。解析側（parse/）は SDK を持たないので問い合わせられない。
//	決めた結果は SDK も STEP も知らない値（core/ImportOptions.h）として解析側へ渡る
//	——Document と同じ「フェーズ間で運ぶ値」である（CLAUDE.md「依存の向きは厳守する」）。
//
//	【名前ではなく図で選べること】シンボルは名前からは中身が分からない（"床束" と
//	"床束2" のどちらが求める図形かは名前からは決まらない）。そこで選択は**サムネイル付きの
//	ポップアップ**（VWThumbnailPopupCtrl）——VectorWorks 自身の「鋼材断面を選択」などと同じ
//	コントロールで、図は VW がリソースに対して持っているサムネイルそのもの。
//
//	**シンボルの行の下は、シンボルを置く行ではない。** 1 行目は**図面枠（タイトルブロック）の
//	スタイル**を選ぶ行（M28）で、候補は図面のシンボル定義のうち `GetSymbolDefSubType` が 552 の
//	もの——他の行が 0（普通のシンボル定義）を並べるのと表裏の関係にある（実装の冒頭）。
//	チェックを外せば図面枠を置かない（この設定を入れる前と同じ）。図面にスタイルがあれば
//	初期値は「一覧の最初のスタイルで置く」。その下に寸法規格（M31）・垂木の断面（M37）の
//	行と、いちばん下の伏図のまとめ方（下記）が続く。
//
//	**行は縦に積まず 2 列に折る。** サムネイルの大きさは選べないので 1 行の高さは決まって
//	いて、役割の数の分だけ縦に並べると画面に対して細長くなりすぎる（実装の冒頭「縦に積まず…」）。
//
//	**それを構築できなかったときは、名前のプルダウン＋シンボル表示コントロールという確実に
//	表示できる形へ切り替えて開き直す。** 設定ダイアログが表示されないままインポートが進むのが
//	最悪なので、外観より「必ず表示されること」を優先する（どちらの形で表示したかはログに残る。
//	実装の冒頭）。
//
//	【行ごとに「取り込む」のチェックがある】置きたいシンボルが図面に無いことは普通にある
//	（テンプレート未適用・その要素を使わない案件）。チェックを外せばその要素は取り込まれず、
//	解析側は命令を 1 つも生成しない。そのため**候補は図面に実在するシンボルだけ**でよくなる
//	——「図面に無い名前」を選択肢に混ぜる必要が無い（core/ImportOptions.h の doc も参照）。
//
//	【伏図のまとめ方】いちばん下に、**横架材の高さごとに生成する伏図**のうち「前のレベルと同じ
//	伏図にまとめる」高さを選ぶチェックを並べる（docs/DEV-NOTES.md「横架材の高さごとに伏図を
//	作る」）。どんな高さがあるかは IFC を読まないと分からないので、呼び出し側が取り込みの前に
//	1 度だけ IFC を読んで候補を渡す（parse/BuildDocument の scanPlanLevelChoices）。まとめる
//	相手の無い高さ（各階の最も低い高さ）は並べない——同じ階に高さが 1 つしかない建物では
//	この欄ごと表示されない。
//
//	【SDK 依存】実装は PluginPrefix.h（VectorWorks SDK）を include する。このヘッダは
//	core/ImportOptions.h までしか参照しないので、SDK を持たない翻訳単位からも安全に
//	include できる。
//

#pragma once

#include "core/ImportOptions.h"

#include <string>
#include <vector>

namespace HomeskzIfcImport::draw
{
	// 設定ダイアログの結果。
	enum class SettingsOutcome
	{
		Accepted,  // 「取り込む」を押した（options に選択が入っている）
		Cancelled, // 「キャンセル」を押した（取り込みは行わない）
		Unavailable, // ダイアログを構築できなかった（**取り込みは既定の対応で続ける**）
	};

	// 取り込み設定ダイアログを 1 枚表示する。
	//
	// 初期値は**同じ VectorWorks を起動している間の前回の選択**で、初回は役割の表の既定名
	// （core::symbolRoles()）。「取り込む」で確定した内容は次回の初期値として記憶する
	// （図面が変わっても記憶している。図面ごとに違うシンボルを使う場合は毎回選び直す）。
	//
	// 選択肢は**現在開いている図面のシンボル定義**（名前順）だけ——ポップアップの項目は
	// 実在するリソースなので、そもそも図面に無い名前は項目にできない。プラグインはシンボル
	// 定義を生成しない（draw/Symbol.cpp）ので、図面に無いものは配置できず、その要素は
	// チェックを外して取り込まない、という形にする。**現在の対応先が図面に無い行は、
	// はじめからチェックの外れた状態で開く**（通知なしに別のシンボルへ差し替わらない）。
	//
	// Unavailable のときは options を変更しない（呼び出し側は既定の対応でそのまま取り込む
	// ——設定を表示できないことを理由に取り込み自体を中止しない。結果ダイアログの代替手段
	// （draw/ResultDialog.h）と同じ考え方。docs/DEV-NOTES.md「取り込み設定の決め事（M20）」）。
	//
	// note に nullptr でない値を渡すと、**どの形で表示したか・表示できなかったならその原因**
	// を 1 行に入れる（何も無ければ空のまま）。呼び出し側はこれを取り込みログへ出力する
	// ——「設定ダイアログが表示されない」という報告の切り分けは、ここを読むところから始まる。
	//
	// planLevels は伏図レベルの候補（まとめる前の横架材の高さ 1 つずつ。
	// parse/BuildDocument の scanPlanLevelChoices）。空ならまとめ方の欄を表示しない。
	SettingsOutcome showImportSettings(core::ImportOptions& options,
									   const std::vector<core::PlanLevelChoice>& planLevels,
									   std::string* note = nullptr);

	// **ダイアログを表示せずに、現在開いている図面から既定の設定を構築する**（M40）。実機テストの
	// 自動の 1 周目（MCP の `vw_run_test` に IFC を名指しされた周）が、テンプレートから
	// 開いた図面に対して呼ぶ。中身は「まだ一度も決めていないときにダイアログが開く初期値」
	// と同じ（core::presetImportOptions）で、**この起動中に人が選んだ前回の値は使わない**
	// ——無人の周の条件が、その日に人が何を押したかで変わらないように。
	//
	// 図面から収集できなかったら false（options は変更しない。note に理由を追加する）。
	bool presetImportSettings(core::ImportOptions& options, std::string* note = nullptr);
} // namespace HomeskzIfcImport::draw
